-- Run after create_database.sql.
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

-- One row per device ping. GEO_LOCATION is populated from longitude/latitude
-- by load_data.sql and can be rebuilt with spatial_queries.sql.
CREATE TABLE IF NOT EXISTS GPS_PINGS (
    DEVICE_ID VARCHAR(20) NOT NULL,
    LATITUDE FLOAT NOT NULL,
    LONGITUDE FLOAT NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP_NTZ NOT NULL,
    LOCATION_TYPE VARCHAR(20) NOT NULL,
    GEO_LOCATION GEOGRAPHY
);

CREATE TABLE IF NOT EXISTS STORE_LOCATIONS (
    STORE_ID VARCHAR(20) NOT NULL,
    STORE_NAME VARCHAR(100) NOT NULL,
    LATITUDE FLOAT NOT NULL,
    LONGITUDE FLOAT NOT NULL,
    GEO_LOCATION GEOGRAPHY
);

CREATE TABLE IF NOT EXISTS COMMERCIAL_ZONES (
    ZONE_ID VARCHAR(20) NOT NULL,
    ZONE_NAME VARCHAR(100) NOT NULL,
    LATITUDE FLOAT NOT NULL,
    LONGITUDE FLOAT NOT NULL,
    RADIUS_METERS NUMBER(10, 2) NOT NULL,
    GEO_LOCATION GEOGRAPHY
);
