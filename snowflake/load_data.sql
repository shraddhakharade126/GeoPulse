-- This idempotent load script is run by scripts/load_to_snowflake.py.
-- The Python connector first PUTs each existing CSV to the matching folder in
-- GEOPULSE_UPLOAD_STAGE. COPY loads into session temporary tables, then MERGE
-- updates or inserts by the source's stable IDs and GPS device/timestamp key.
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

CREATE OR REPLACE TEMPORARY TABLE GPS_PINGS_LOAD (
    DEVICE_ID VARCHAR(20),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    EVENT_TIMESTAMP TIMESTAMP_NTZ,
    LOCATION_TYPE VARCHAR(20)
);

COPY INTO GPS_PINGS_LOAD
FROM @GEOPULSE_DB.RAW.GEOPULSE_UPLOAD_STAGE/gps_pings/
FILE_FORMAT = (FORMAT_NAME = GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT'
FORCE = TRUE
PURGE = TRUE;

CREATE OR REPLACE TEMPORARY TABLE STORE_LOCATIONS_LOAD (
    STORE_ID VARCHAR(20),
    STORE_NAME VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT
);

COPY INTO STORE_LOCATIONS_LOAD
FROM @GEOPULSE_DB.RAW.GEOPULSE_UPLOAD_STAGE/store_locations/
FILE_FORMAT = (FORMAT_NAME = GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT'
FORCE = TRUE
PURGE = TRUE;

CREATE OR REPLACE TEMPORARY TABLE COMMERCIAL_ZONES_LOAD (
    ZONE_ID VARCHAR(20),
    ZONE_NAME VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    RADIUS_METERS NUMBER(10, 2)
);

COPY INTO COMMERCIAL_ZONES_LOAD
FROM @GEOPULSE_DB.RAW.GEOPULSE_UPLOAD_STAGE/commercial_zones/
FILE_FORMAT = (FORMAT_NAME = GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT'
FORCE = TRUE
PURGE = TRUE;

MERGE INTO GEOPULSE_DB.RAW.GPS_PINGS AS target
USING (
    SELECT
        DEVICE_ID,
        LATITUDE,
        LONGITUDE,
        EVENT_TIMESTAMP,
        LOCATION_TYPE,
        ST_MAKEPOINT(LONGITUDE, LATITUDE) AS GEO_LOCATION
    FROM GPS_PINGS_LOAD
) AS source
ON target.DEVICE_ID = source.DEVICE_ID
   AND target.EVENT_TIMESTAMP = source.EVENT_TIMESTAMP
WHEN MATCHED THEN UPDATE SET
    LATITUDE = source.LATITUDE,
    LONGITUDE = source.LONGITUDE,
    LOCATION_TYPE = source.LOCATION_TYPE,
    GEO_LOCATION = source.GEO_LOCATION
WHEN NOT MATCHED THEN INSERT (
    DEVICE_ID, LATITUDE, LONGITUDE, EVENT_TIMESTAMP, LOCATION_TYPE, GEO_LOCATION
) VALUES (
    source.DEVICE_ID, source.LATITUDE, source.LONGITUDE, source.EVENT_TIMESTAMP,
    source.LOCATION_TYPE, source.GEO_LOCATION
);

MERGE INTO GEOPULSE_DB.RAW.STORE_LOCATIONS AS target
USING (
    SELECT
        STORE_ID,
        STORE_NAME,
        LATITUDE,
        LONGITUDE,
        ST_MAKEPOINT(LONGITUDE, LATITUDE) AS GEO_LOCATION
    FROM STORE_LOCATIONS_LOAD
) AS source
ON target.STORE_ID = source.STORE_ID
WHEN MATCHED THEN UPDATE SET
    STORE_NAME = source.STORE_NAME,
    LATITUDE = source.LATITUDE,
    LONGITUDE = source.LONGITUDE,
    GEO_LOCATION = source.GEO_LOCATION
WHEN NOT MATCHED THEN INSERT (
    STORE_ID, STORE_NAME, LATITUDE, LONGITUDE, GEO_LOCATION
) VALUES (
    source.STORE_ID, source.STORE_NAME, source.LATITUDE, source.LONGITUDE,
    source.GEO_LOCATION
);

MERGE INTO GEOPULSE_DB.RAW.COMMERCIAL_ZONES AS target
USING (
    SELECT
        ZONE_ID,
        ZONE_NAME,
        LATITUDE,
        LONGITUDE,
        RADIUS_METERS,
        ST_MAKEPOINT(LONGITUDE, LATITUDE) AS GEO_LOCATION
    FROM COMMERCIAL_ZONES_LOAD
) AS source
ON target.ZONE_ID = source.ZONE_ID
WHEN MATCHED THEN UPDATE SET
    ZONE_NAME = source.ZONE_NAME,
    LATITUDE = source.LATITUDE,
    LONGITUDE = source.LONGITUDE,
    RADIUS_METERS = source.RADIUS_METERS,
    GEO_LOCATION = source.GEO_LOCATION
WHEN NOT MATCHED THEN INSERT (
    ZONE_ID, ZONE_NAME, LATITUDE, LONGITUDE, RADIUS_METERS, GEO_LOCATION
) VALUES (
    source.ZONE_ID, source.ZONE_NAME, source.LATITUDE, source.LONGITUDE,
    source.RADIUS_METERS, source.GEO_LOCATION
);
