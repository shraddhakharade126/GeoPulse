-- Rebuild GEOGRAPHY values if a table was populated without the loader.
-- ST_MAKEPOINT takes longitude first and latitude second.
UPDATE GEOPULSE_DB.RAW.GPS_PINGS
SET GEO_LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE)
WHERE GEO_LOCATION IS NULL;

UPDATE GEOPULSE_DB.RAW.STORE_LOCATIONS
SET GEO_LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE)
WHERE GEO_LOCATION IS NULL;

UPDATE GEOPULSE_DB.RAW.COMMERCIAL_ZONES
SET GEO_LOCATION = ST_MAKEPOINT(LONGITUDE, LATITUDE)
WHERE GEO_LOCATION IS NULL;

-- Store A is STORE001. Distances returned for GEOGRAPHY are in meters.
SELECT
    gps.DEVICE_ID,
    gps.EVENT_TIMESTAMP,
    store.STORE_ID,
    store.STORE_NAME,
    ST_DISTANCE(gps.GEO_LOCATION, store.GEO_LOCATION) AS DISTANCE_METERS
FROM GEOPULSE_DB.RAW.GPS_PINGS AS gps
JOIN GEOPULSE_DB.RAW.STORE_LOCATIONS AS store
    ON store.STORE_ID = 'STORE001'
WHERE gps.GEO_LOCATION IS NOT NULL
  AND store.GEO_LOCATION IS NOT NULL
ORDER BY DISTANCE_METERS
LIMIT 25;

-- Filter GPS pings within 500 meters of Store A.
SELECT
    gps.DEVICE_ID,
    gps.EVENT_TIMESTAMP,
    gps.LATITUDE,
    gps.LONGITUDE,
    ST_DISTANCE(gps.GEO_LOCATION, store.GEO_LOCATION) AS DISTANCE_METERS
FROM GEOPULSE_DB.RAW.GPS_PINGS AS gps
JOIN GEOPULSE_DB.RAW.STORE_LOCATIONS AS store
    ON store.STORE_ID = 'STORE001'
WHERE ST_DWITHIN(gps.GEO_LOCATION, store.GEO_LOCATION, 500)
ORDER BY DISTANCE_METERS;

-- Count GPS pings within 500 meters of every store.
SELECT
    store.STORE_ID,
    store.STORE_NAME,
    COUNT(gps.DEVICE_ID) AS GPS_PINGS_WITHIN_500M
FROM GEOPULSE_DB.RAW.STORE_LOCATIONS AS store
LEFT JOIN GEOPULSE_DB.RAW.GPS_PINGS AS gps
    ON ST_DWITHIN(gps.GEO_LOCATION, store.GEO_LOCATION, 500)
GROUP BY store.STORE_ID, store.STORE_NAME
ORDER BY GPS_PINGS_WITHIN_500M DESC, store.STORE_ID;

-- Spatial filtering example: all pings within the first store's commercial radius.
SELECT COUNT(*) AS PINGS_WITHIN_STORE_ZONE_RADIUS
FROM GEOPULSE_DB.RAW.GPS_PINGS AS gps
JOIN GEOPULSE_DB.RAW.STORE_LOCATIONS AS store
    ON store.STORE_ID = 'STORE001'
WHERE ST_DWITHIN(gps.GEO_LOCATION, store.GEO_LOCATION, 500);
