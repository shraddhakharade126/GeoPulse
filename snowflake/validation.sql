-- Compare these expected source counts with the existing CSVs:
-- gps_pings.csv = 100000, store_locations.csv = 12, commercial_zones.csv = 8.
SELECT 'GPS_PINGS' AS TABLE_NAME, COUNT(*) AS ACTUAL_ROWS, 100000 AS EXPECTED_ROWS,
       IFF(COUNT(*) = 100000, 'PASS', 'CHECK') AS RESULT
FROM GEOPULSE_DB.RAW.GPS_PINGS
UNION ALL
SELECT 'STORE_LOCATIONS', COUNT(*), 12, IFF(COUNT(*) = 12, 'PASS', 'CHECK')
FROM GEOPULSE_DB.RAW.STORE_LOCATIONS
UNION ALL
SELECT 'COMMERCIAL_ZONES', COUNT(*), 8, IFF(COUNT(*) = 8, 'PASS', 'CHECK')
FROM GEOPULSE_DB.RAW.COMMERCIAL_ZONES;

SELECT
    COUNT(*) AS TOTAL_GPS_RECORDS,
    COUNT(DISTINCT DEVICE_ID) AS UNIQUE_DEVICES,
    COALESCE(COUNT_IF(DEVICE_ID IS NULL), 0) AS MISSING_DEVICE_IDS,
    COALESCE(COUNT_IF(LATITUDE IS NULL OR LONGITUDE IS NULL), 0) AS MISSING_COORDINATES,
    COALESCE(COUNT_IF(LATITUDE NOT BETWEEN 18.40 AND 18.65), 0) AS OUT_OF_RANGE_LATITUDE,
    COALESCE(COUNT_IF(LONGITUDE NOT BETWEEN 73.75 AND 74.00), 0) AS OUT_OF_RANGE_LONGITUDE,
    COALESCE(COUNT_IF(EVENT_TIMESTAMP IS NULL), 0) AS MISSING_TIMESTAMPS,
    COALESCE(COUNT_IF(GEO_LOCATION IS NULL), 0) AS MISSING_GEOGRAPHY_POINTS
FROM GEOPULSE_DB.RAW.GPS_PINGS;

-- A duplicate is a repeated complete source record, ignoring the derived point.
SELECT COALESCE(SUM(RECORD_COUNT - 1), 0) AS DUPLICATE_GPS_RECORDS
FROM (
    SELECT COUNT(*) AS RECORD_COUNT
    FROM GEOPULSE_DB.RAW.GPS_PINGS
    GROUP BY DEVICE_ID, LATITUDE, LONGITUDE, EVENT_TIMESTAMP, LOCATION_TYPE
    HAVING COUNT(*) > 1
);

SELECT
    COUNT(*) AS STORE_RECORDS,
    COALESCE(COUNT_IF(STORE_ID IS NULL OR STORE_NAME IS NULL), 0) AS MISSING_STORE_FIELDS,
    COALESCE(COUNT_IF(GEO_LOCATION IS NULL), 0) AS MISSING_STORE_POINTS,
    COALESCE(COUNT_IF(LATITUDE NOT BETWEEN 18.40 AND 18.65), 0) AS OUT_OF_RANGE_LATITUDE,
    COALESCE(COUNT_IF(LONGITUDE NOT BETWEEN 73.75 AND 74.00), 0) AS OUT_OF_RANGE_LONGITUDE
FROM GEOPULSE_DB.RAW.STORE_LOCATIONS;

SELECT
    COUNT(*) AS COMMERCIAL_ZONE_RECORDS,
    COALESCE(COUNT_IF(ZONE_ID IS NULL OR ZONE_NAME IS NULL OR RADIUS_METERS IS NULL), 0)
        AS MISSING_ZONE_FIELDS,
    COALESCE(COUNT_IF(GEO_LOCATION IS NULL), 0) AS MISSING_ZONE_POINTS,
    COALESCE(COUNT_IF(RADIUS_METERS <= 0), 0) AS INVALID_RADII,
    COALESCE(COUNT_IF(LATITUDE NOT BETWEEN 18.40 AND 18.65), 0) AS OUT_OF_RANGE_LATITUDE,
    COALESCE(COUNT_IF(LONGITUDE NOT BETWEEN 73.75 AND 74.00), 0) AS OUT_OF_RANGE_LONGITUDE
FROM GEOPULSE_DB.RAW.COMMERCIAL_ZONES;
